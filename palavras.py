# ============================================================
# LIMPEZA AUTOMÁTICA
# ============================================================

# Esta parte impede que números, listas numéricas ou
# palavras duplicadas entrem no jogo.

PALAVRAS_LIMPAS = []

PALAVRAS_VISTAS = set()

for palavra in PALAVRAS:

    if not isinstance(palavra, str):
        continue

    palavra = palavra.strip().lower()

    if not palavra:
        continue

    # Aceita somente palavras formadas por letras.
    if not palavra.isalpha():
        continue

    if palavra in PALAVRAS_VISTAS:
        continue

    PALAVRAS_VISTAS.add(palavra)

    PALAVRAS_LIMPAS.append(palavra)


# ============================================================
# BANCO DEFINITIVO
# ============================================================

PALAVRAS = PALAVRAS_LIMPAS


